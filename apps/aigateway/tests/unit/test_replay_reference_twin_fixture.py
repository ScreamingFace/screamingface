"""The gateway PRODUCES the live/replay twin fixture the Engine's price-parity test consumes.

FEATURE (E4c ans:Q21b, budget BU-27, OME-1291; review of PR #1733): one price source live and
on replay. A budget Gate reads the price of each earlier call; on a frozen-copy replay the
gateway renders the captured call's price as ``cache.reference``. The Engine must read the same
numbers from both blocks, or a replay takes another branch.

The fixture ``tests/fixtures/replay_reference_twins/twins.json`` is not written by hand. For each
case this test renders the live ``_aigw`` block with the real renderer, renders its replay with
the real replay route function (``_replay_metadata``), normalizes the per-run call id, and
compares the result to the file. The Engine suite
(``apps/screamingface-engine/tests/unit/test_e4c_replay_price_parity_twin.py``) reads the same
file by repository path; apps never import each other. So a change to the replay rule fails here
until the fixture is regenerated, and the regenerated fixture runs the Engine check.

AIDEV-NOTE: regenerate with ``SF_REGENERATE_CONTRACT_FIXTURES=1 uv run pytest
tests/unit/test_replay_reference_twin_fixture.py``, then run the Engine parity twin test.
Residual gap (not in the fixture): a usage block with a bogus ``status`` but valid counts. The
gateway refuses that block (strict ``TokenUsage``); the Engine reads its counts. A live gateway
never renders it, so only a corrupted capture can hold it.
"""

from __future__ import annotations

import json
import os
import re
from pathlib import Path
from typing import Any

import pytest

from aigateway.plugins.taxonomy import DirectCost
from aigateway.routes.frozen_copies import _replay_metadata
from tests.unit.test_frozen_copy_replay_reference import (
    _failed,
    _live_hit,
    _live_miss,
    _record,
    _stored,
)

FIXTURE = Path(__file__).resolve().parents[1] / "fixtures/replay_reference_twins/twins.json"
REGENERATE = "SF_REGENERATE_CONTRACT_FIXTURES"
_CALL_ID = "call_" + "0" * 32
_CALL_ID_RE = re.compile(r"call_[0-9a-f]{32}")


def _edited(aigw: dict[str, Any], **attempt: Any) -> dict[str, Any]:
    """A captured block whose priced attempt holds a malformed dimension."""
    aigw["usage_accounting"]["attempts"][-1].update(attempt)
    return aigw


def _hit_with(**reference: Any) -> dict[str, Any]:
    aigw = _live_hit(_stored())
    aigw["usage_accounting"]["cache"]["reference"].update(reference)
    return aigw


def _cases() -> dict[str, dict[str, Any]]:
    usd = DirectCost.reported(amount="0.25", unit="usd", source="provider.usage.cost")
    return {
        "reported": _live_miss(_record(1)),
        "retry": _live_miss(_failed(1), _record(2)),
        "usd-unit": _live_miss(_record(1, direct_cost=usd)),
        "unavailable-cost": _live_miss(_record(1, direct_cost=DirectCost.unavailable())),
        "partial-capture": _live_miss(_record(1), status="partial"),
        "no-success": _live_miss(_failed(1)),
        "captured-hit": _live_hit(_stored()),
        "malformed-usage": _edited(_live_miss(_record(1)), usage="garbage"),
        "malformed-cost": _edited(_live_miss(_record(1)), direct_cost="garbage"),
        "bogus-cost-status": _edited(_live_miss(_record(1)), direct_cost={"status": "bogus"}),
        "negative-latency": _edited(_live_miss(_record(1)), latency_ms=-5),
        "bool-latency": _edited(_live_miss(_record(1)), latency_ms=True),
        "hit-malformed-usage": _hit_with(usage="garbage"),
    }


def _normalized(aigw: dict[str, Any]) -> dict[str, Any]:
    accounting = aigw["usage_accounting"]
    assert _CALL_ID_RE.fullmatch(accounting["gateway_call_id"])
    accounting["gateway_call_id"] = _CALL_ID
    return aigw


def _produced() -> dict[str, Any]:
    twins = {}
    for name, live in _cases().items():
        replay = _replay_metadata(live)
        assert replay.get("trace_id") is None, "a trace id outside a request is not stable"
        twins[name] = {"live": _normalized(live), "replay": _normalized(replay)}
    return {
        "description": (
            "Live _aigw blocks and the frozen-copy replay block the gateway renders for each. "
            "Generated by apps/aigateway/tests/unit/test_replay_reference_twin_fixture.py; "
            f"regenerate with {REGENERATE}=1. The call id is normalized."
        ),
        "twins": twins,
    }


def _regenerate(produced: dict[str, Any]) -> None:
    """Write the fixture, then FAIL, so a regeneration run never looks like a green build."""
    if os.environ.get("CI"):
        pytest.fail(f"{REGENERATE}=1 is refused under CI; regenerate locally.", pytrace=False)
    FIXTURE.parent.mkdir(parents=True, exist_ok=True)
    FIXTURE.write_text(json.dumps(produced, indent=2) + "\n", encoding="utf-8")
    pytest.fail(
        f"replay twin fixture regenerated at {FIXTURE.name}. Review the diff, run the Engine "
        "parity twin test, commit, then re-run plainly.",
        pytrace=False,
    )


def test_the_checked_in_twins_are_what_the_gateway_renders() -> None:
    produced = json.loads(json.dumps(_produced()))
    if os.environ.get(REGENERATE) == "1":
        _regenerate(produced)
    assert FIXTURE.exists(), f"missing {FIXTURE}; generate it with {REGENERATE}=1"
    assert json.loads(FIXTURE.read_text(encoding="utf-8")) == produced, (
        f"the replay rule changed. If that is deliberate, regenerate with {REGENERATE}=1 and "
        "run the Engine parity twin test."
    )


def test_the_twins_hold_priced_and_unpriced_replays() -> None:
    """Guards the Engine check from passing on blocks that all carry no price."""
    twins = json.loads(FIXTURE.read_text(encoding="utf-8"))["twins"]
    references = {
        name: twin["replay"]["usage_accounting"]["cache"]["reference"]
        for name, twin in twins.items()
    }
    assert references["retry"]["direct_cost"]["amount"] == "0.002"
    assert references["usd-unit"]["direct_cost"]["unit"] == "usd"
    assert references["partial-capture"] is None
    assert references["no-success"] is None
    assert references["malformed-usage"]["direct_cost"]["amount"] == "0.001"
